// Validates content/stage*/dNN.json and writes data.js (const KIDS_TALK).
// Usage: node tools/build-content.js   (exits 1 if any issue)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const TOPICS = new Set(["daily", "ships", "planes", "space", "science"]);
const WHO = new Set(["parent", "kid"]);
const issues = [];
const err = (f, m) => issues.push(`${f}: ${m}`);
const norm = s => s.toLowerCase().replace(/[’‘]/g, "'").replace(/[^a-z0-9' ]+/g, " ").replace(/\s+/g, " ").trim();

function checkDay(file, d) {
    for (const k of ["stage", "day", "topic", "title_en", "title_ko", "intro_ko", "expressions", "script", "talkMore", "kidQuiz", "parentQuiz"])
        if (d[k] === undefined) err(file, `missing ${k}`);
    if (!TOPICS.has(d.topic)) err(file, `bad topic ${d.topic}`);
    const exp = d.expressions || [], script = d.script || [];
    if (exp.length < 4 || exp.length > 5) err(file, `expressions ${exp.length} (want 4-5)`);
    if (script.length < 18 || script.length > 24) err(file, `script ${script.length} lines (want 18-24)`);
    const all = " " + script.map(l => norm(l.en || "")).join(" | ") + " ";
    exp.forEach((e, i) => {
        if (!e.en || !e.ko || !e.tip || !["parent", "kid", "both"].includes(e.who)) err(file, `expression ${i} incomplete`);
        // "…" marks a slot ("Can I have some …?"): each fixed part must appear.
        const parts = (e.en || "").split(/…|\.\.\./).map(norm).filter(Boolean);
        if (parts.some(p => !all.includes(" " + p + " ") && !all.includes(" " + p) && !all.includes(p))) err(file, `expression not in script: "${e.en}"`);
    });
    let practice = 0;
    script.forEach((l, i) => {
        if (!WHO.has(l.who) || !l.en || !l.ko) err(file, `script ${i} incomplete`);
        if (/[“”‘’]/.test(l.en || "")) err(file, `script ${i} curly quotes`);
        if (/\b(mom|mommy|dad|daddy)\b/i.test(l.en || "")) err(file, `script ${i} addresses Mom/Dad`);
        const words = (l.en || "").split(/\s+/).length;
        if (l.who === "kid" && words > 8) err(file, `script ${i} kid line ${words} words`);
        if (l.who === "parent" && words > 14) err(file, `script ${i} parent line ${words} words`);
        if (l.practice) { practice++; if (l.who !== "kid") err(file, `script ${i} practice on parent line`); }
    });
    if (practice < 4 || practice > 8) err(file, `practice lines ${practice} (want 4-8)`);
    if ((d.talkMore || []).length !== 3) err(file, `talkMore ${(d.talkMore || []).length} (want 3)`);
    (d.talkMore || []).forEach((t, i) => { if (!t.en || !t.ko || !t.sample_en || !t.sample_ko) err(file, `talkMore ${i} incomplete`); });
    if ((d.kidQuiz || []).length !== 10) err(file, `kidQuiz ${(d.kidQuiz || []).length} (want 10)`);
    (d.kidQuiz || []).forEach((q, i) => {
        if (!q.prompt_en || !q.prompt_ko) err(file, `kidQuiz ${i} prompt missing`);
        const o = q.options || [];
        if (o.length !== 3 || o.some(x => !x.e || !x.en)) err(file, `kidQuiz ${i} needs 3 {e,en} options`);
        if (new Set(o.map(x => norm(x.en || ""))).size !== o.length) err(file, `kidQuiz ${i} duplicate options`);
    });
    if ((d.parentQuiz || []).length !== 10) err(file, `parentQuiz ${(d.parentQuiz || []).length} (want 10)`);
    (d.parentQuiz || []).forEach((q, i) => {
        const o = q.options || [];
        if (!q.q || !q.explain) err(file, `parentQuiz ${i} q/explain missing`);
        if (o.length !== 4 || new Set(o.map(x => String(x).trim())).size !== 4) err(file, `parentQuiz ${i} needs 4 distinct options`);
    });
}

const stages = [];
for (const dir of fs.readdirSync(path.join(root, "content")).filter(n => /^stage\d+$/.test(n)).sort()) {
    const stage = +dir.slice(5);
    const files = fs.readdirSync(path.join(root, "content", dir)).filter(n => /^d\d+\.json$/.test(n)).sort();
    const days = [];
    for (const f of files) {
        const rel = `content/${dir}/${f}`;
        let d;
        try { d = JSON.parse(fs.readFileSync(path.join(root, rel), "utf8")); } catch (e) { err(rel, "bad JSON: " + e.message); continue; }
        if (d.stage !== stage || d.day !== +f.slice(1, -5)) err(rel, `stage/day fields do not match file name`);
        checkDay(rel, d);
        days.push(d);
    }
    days.sort((a, b) => a.day - b.day);
    const have = new Set(days.map(d => d.day)), max = Math.max(0, ...have);
    for (let n = 1; n <= max; n++) if (!have.has(n)) err(`content/${dir}`, `day ${n} missing`);
    stages.push({ stage, days });
}

const out = "// Generated by tools/build-content.js from content/ — do not edit by hand.\nconst KIDS_TALK = " + JSON.stringify({ stages }) + ";\n";
fs.writeFileSync(path.join(root, "data.js"), out);
const n = stages.reduce((s, x) => s + x.days.length, 0);
console.log(`${n} days in ${stages.length} stage(s) -> data.js (${(out.length / 1024).toFixed(0)} KB)`);
if (issues.length) { console.log(issues.length + " issue(s):\n" + issues.join("\n")); process.exit(1); }
console.log("0 issues");
